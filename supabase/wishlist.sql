-- =====================================================================
--  Wishlist / Save-for-later, used by the chat shopping agent.
--  Run this in the Supabase SQL Editor AFTER schema.sql.
-- =====================================================================

create table if not exists saved_items (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references products(id) on delete cascade,
  kind       text not null check (kind in ('wishlist', 'saved_for_later')),
  created_at timestamptz default now(),
  unique (user_id, product_id, kind)
);

create index if not exists saved_items_user_idx on saved_items (user_id);

alter table saved_items enable row level security;

create policy "own saved_items select" on saved_items for select using (auth.uid() = user_id);
create policy "own saved_items insert" on saved_items for insert with check (auth.uid() = user_id);
create policy "own saved_items delete" on saved_items for delete using (auth.uid() = user_id);
