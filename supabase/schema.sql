create extension if not exists vector;

-- ---------------------------------------------------------------------
--  Drop in dependency order (children first)
-- ---------------------------------------------------------------------
drop table if exists cart_items     cascade;
drop table if exists product_spec   cascade;
drop table if exists product_variants cascade;
drop table if exists products       cascade;
drop table if exists category       cascade;

-- ---------------------------------------------------------------------
--  Tables
-- ---------------------------------------------------------------------
create table category (
  id            bigint generated by default as identity primary key,
  category_name text not null unique
);

create table products (
  id               bigint generated by default as identity primary key,
  name             text not null,
  description      text,
  image_url        text,
  stock            int     default 0,
  bestseller       boolean default false,
  rating           numeric(2,1),
  review_count     int     default 0,
  discount_percent numeric(5,2) default 0,
  category_id      bigint references category(id) on delete set null,
  created_at       timestamptz default now(),

  -- Lexical search: generated tsvector kept in sync automatically
  fts tsvector generated always as (
    to_tsvector('english', coalesce(name, '') || ' ' || coalesce(description, ''))
  ) stored,

  -- Semantic search: 384 dims = gte-small embedding size
  embedding vector(384)
);

create table product_variants (
  id               bigint generated by default as identity primary key,
  product_id       bigint references products(id) on delete cascade,
  color            text,
  size             text,
  price            numeric(10,2) not null default 0,
  stock            int default 0,
  image_url        text,
  discount_percent numeric(5,2) default 0
);

create table product_spec (
  id         bigint generated by default as identity primary key,
  product_id bigint references products(id) on delete cascade,
  spec_name  text not null,
  spec_value text
);

create table cart_items (
  id                 bigint generated by default as identity primary key,
  user_id            uuid not null references auth.users(id) on delete cascade,
  product_id         bigint references products(id) on delete cascade,
  product_variant_id bigint references product_variants(id) on delete cascade,
  quantity           int not null default 1,
  created_at         timestamptz default now()
);

-- ---------------------------------------------------------------------
--  Indexes
-- ---------------------------------------------------------------------
create index products_fts_idx       on products using gin  (fts);
create index products_embedding_idx on products using hnsw (embedding vector_cosine_ops);
create index products_category_idx  on products (category_id);
create index variants_product_idx   on product_variants (product_id);
create index spec_product_idx       on product_spec (product_id);
create index cart_user_idx          on cart_items (user_id);

-- ---------------------------------------------------------------------
--  Row Level Security
--    Catalog tables: public read only.
--    cart_items:     each user sees/edits only their own rows.
-- ---------------------------------------------------------------------
alter table category         enable row level security;
alter table products         enable row level security;
alter table product_variants enable row level security;
alter table product_spec     enable row level security;
alter table cart_items       enable row level security;

create policy "public read category"  on category         for select using (true);
create policy "public read products"  on products         for select using (true);
create policy "public read variants"  on product_variants for select using (true);
create policy "public read spec"      on product_spec     for select using (true);

create policy "own cart select" on cart_items for select using (auth.uid() = user_id);
create policy "own cart insert" on cart_items for insert with check (auth.uid() = user_id);
create policy "own cart update" on cart_items for update using (auth.uid() = user_id);
create policy "own cart delete" on cart_items for delete using (auth.uid() = user_id);

-- =====================================================================
--  Hybrid search function (Reciprocal Rank Fusion of FTS + vector)
-- =====================================================================
create or replace function hybrid_search(
  query_text       text,
  query_embedding  vector(384),
  match_count      int   default 12,
  full_text_weight float default 1,
  semantic_weight  float default 1,
  rrf_k            int   default 50
)
returns setof products
language sql
as $$
with full_text as (
  select
    id,
    row_number() over (
      order by ts_rank_cd(fts, websearch_to_tsquery('english', query_text)) desc
    ) as rank_ix
  from products
  where fts @@ websearch_to_tsquery('english', query_text)
  order by rank_ix
  limit least(match_count, 30) * 2
),
semantic as (
  select
    id,
    row_number() over (order by embedding <=> query_embedding) as rank_ix
  from products
  where embedding is not null
  order by rank_ix
  limit least(match_count, 30) * 2
)
select products.*
from full_text
full outer join semantic on full_text.id = semantic.id
join products on coalesce(full_text.id, semantic.id) = products.id
order by
  coalesce(1.0 / (rrf_k + full_text.rank_ix), 0.0) * full_text_weight +
  coalesce(1.0 / (rrf_k + semantic.rank_ix), 0.0) * semantic_weight
  desc
limit least(match_count, 30);
$$;

